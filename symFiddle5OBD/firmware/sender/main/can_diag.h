/* CAN 物理层诊断（手机串口查看版）。
 *
 * 每轮约 5~7 秒，插上电就一直循环，手机随时连上串口都能读到完整的一轮。
 * 输出刻意做得很短（6~9 行），不用 ESP_LOG 的时间戳前缀，
 * 手机竖屏看不用横向滚。
 *
 * 测六件事：
 *   1. RX 线有没有真的接到收发器（切内部上下拉）
 *   2. 裸采 RX 有没有边沿（收发器有没有在输出数据）
 *   3. TX 通路（NO_ACK 自发，看位错误）
 *   4. ACK 测试（往总线发非诊断 ID，看有没有 ECU 应答）
 *   5. 500k 监听，必要时再试 250k / 125k / 1M
 *   6. 汇总判定
 *
 * 注意：第 3、4 步会向总线发帧（ID 0x6A5，不是 OBD 诊断 ID），
 * 不会触发任何 ECU 回应。其余步骤只收不发。
 */
